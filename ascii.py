def shift_up(rows, char):
    FONT_5X7[char] = [val >> rows for val in FONT_5X7[char]]


# fixups for some characters with their bottom rows hidden
shift_up(1, "g")
shift_up(1, "p")
shift_up(1, "q")
shift_up(1, "y")


def visualize_char(char):
    if char not in FONT_5X7:
        return
    columns = FONT_5X7[char]
    for row in range(7):
        line = ""
        for col in range(5):
            bit = (columns[col] >> (row)) & 1
            line += "+" if bit else " "
        print("    // " + line + " //")


def generate_full_glsl_array():
    print("const uint FONT_COLUMNS[180] = uint[](")

    chars = [str(d) for d in range(10)] + [chr(ord("a") + i) for i in range(26)]

    for idx, char in enumerate(chars):
        columns = FONT_5X7[char]
        hex_values = ", ".join(f"0x{c:02X}" for c in columns)
        comment = f"// {char} (idx {idx})"
        visualize_char(char)
        if idx < len(chars) - 1:
            print(f"    {hex_values}, {comment}")
        else:
            print(f"    {hex_values}  {comment}")
    print(");")


if __name__ == "__main__":
    generate_full_glsl_array()
